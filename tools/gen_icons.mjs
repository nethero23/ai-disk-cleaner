// Regenerates src/ui/icons.gen.ts from @material-symbols/svg-400 (Rounded, weight 400).
// Only the icons listed here end up in the app. Add a name, then run: node tools/gen_icons.mjs
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const NAMES = [
  "add", "admin_panel_settings", "arrow_back", "arrow_drop_down", "arrow_forward", "arrow_upward", "wand_stars",
  "bedtime", "block", "chat", "check", "chevron_right", "close", "cleaning_services", "cloud_download",
  "compress", "content_copy", "folder", "open_in_new", "palette", "rule", "update", "dark_mode", "delete", "description", "donut_large", "drive_file_move", "error", "extension", "hub", "flag",
  "folder_open", "help", "history", "info", "language", "light_mode", "lock", "more_vert", "radar", "refresh",
  "restore_from_trash", "schedule", "search", "settings", "shield", "sort", "trending_up", "undo", "verified",
  "verified_user", "visibility", "visibility_off", "warning",
];

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "node_modules/@material-symbols/svg-400/rounded");
const path = (file) => readFileSync(join(dir, file), "utf8").match(/ d="([^"]+)"/)[1];

let out = "// Generated by tools/gen_icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n";
out += "export const ICONS = {\n";
for (const n of NAMES) {
  const fill = existsSync(join(dir, `${n}-fill.svg`)) ? path(`${n}-fill.svg`) : path(`${n}.svg`);
  out += `  ${n}: [${JSON.stringify(path(`${n}.svg`))}, ${JSON.stringify(fill)}],\n`;
}
out += "} as const;\n\nexport type IconName = keyof typeof ICONS;\n";
writeFileSync(join(root, "src/ui/icons.gen.ts"), out);
console.log(`wrote ${NAMES.length} icons`);
